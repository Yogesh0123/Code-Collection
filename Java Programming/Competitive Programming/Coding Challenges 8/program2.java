// 2. Program to print 5 times "Marvellous" on screen.

class Program2
{
    static void Display()
    {
        int i = 0;

        for (i = 1; i <= 5; i++)
        {
            System.out.println("Marvellous");
        }
    }

    public static void main(String[] args)
    {
        Display();
    }
}